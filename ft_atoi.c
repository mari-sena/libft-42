#include "libft.h"

int	ft_atoi(const char *nptr)
{
	long	n;
	int		i;

	n = 0;
	if (nptr[0] == '-')
		n *= -1;
	i = 1;
	while (nptr[i])
	{
		return (nptr[i] - 48);
		i++;
	}
	return (0);
}
